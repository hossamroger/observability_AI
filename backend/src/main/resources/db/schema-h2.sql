CREATE TABLE IF NOT EXISTS OBS_METRIC_SNAPSHOT (
  METRIC_ID VARCHAR(36) PRIMARY KEY,
  SOURCE_SYSTEM VARCHAR(40) NOT NULL,
  PLATFORM VARCHAR(25) NOT NULL,
  SERVICE_NAME VARCHAR(180) NOT NULL,
  METRIC_NAME VARCHAR(200) NOT NULL,
  METRIC_VALUE DOUBLE PRECISION NOT NULL,
  METRIC_UNIT VARCHAR(50) NOT NULL,
  WINDOW_START_UTC TIMESTAMP NOT NULL,
  WINDOW_END_UTC TIMESTAMP NOT NULL,
  COLLECTED_AT_UTC TIMESTAMP NOT NULL,
  IS_DEMO INTEGER DEFAULT 0 NOT NULL
);
CREATE INDEX IF NOT EXISTS IDX_OBS_METRIC_RECENT ON OBS_METRIC_SNAPSHOT (COLLECTED_AT_UTC);
CREATE TABLE IF NOT EXISTS OBS_COLLECTION_EXECUTION_LOG (
  EXECUTION_ID VARCHAR(36) PRIMARY KEY,
  SOURCE_SYSTEM VARCHAR(40) NOT NULL,
  OPERATION_NAME VARCHAR(80) NOT NULL,
  EXECUTED_AT_UTC TIMESTAMP NOT NULL,
  STATUS VARCHAR(20) NOT NULL,
  RECORD_COUNT INTEGER NOT NULL,
  DURATION_MS BIGINT NOT NULL,
  ERROR_CATEGORY VARCHAR(140),
  MESSAGE VARCHAR(1000) NOT NULL
);
