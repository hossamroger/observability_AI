-- Execute as DS_OBSERVABILITY schema owner. Review data retention and tablespace quotas.
CREATE TABLE OBS_METRIC_SNAPSHOT (
  METRIC_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  SOURCE_SYSTEM VARCHAR2(40 CHAR) NOT NULL,
  PLATFORM VARCHAR2(25 CHAR) NOT NULL,
  SERVICE_NAME VARCHAR2(180 CHAR) NOT NULL,
  METRIC_NAME VARCHAR2(200 CHAR) NOT NULL,
  METRIC_VALUE BINARY_DOUBLE NOT NULL,
  METRIC_UNIT VARCHAR2(50 CHAR) NOT NULL,
  WINDOW_START_UTC TIMESTAMP(6) NOT NULL,
  WINDOW_END_UTC TIMESTAMP(6) NOT NULL,
  COLLECTED_AT_UTC TIMESTAMP(6) NOT NULL,
  IS_DEMO NUMBER(1) DEFAULT 0 NOT NULL,
  CONSTRAINT CK_OBS_METRIC_DEMO CHECK (IS_DEMO IN (0, 1))
);
CREATE INDEX IDX_OBS_METRIC_RECENT ON OBS_METRIC_SNAPSHOT (COLLECTED_AT_UTC);
CREATE INDEX IDX_OBS_METRIC_DIM ON OBS_METRIC_SNAPSHOT
    (SOURCE_SYSTEM, PLATFORM, METRIC_NAME, COLLECTED_AT_UTC);

CREATE TABLE OBS_COLLECTION_EXECUTION_LOG (
  EXECUTION_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  SOURCE_SYSTEM VARCHAR2(40 CHAR) NOT NULL,
  OPERATION_NAME VARCHAR2(80 CHAR) NOT NULL,
  EXECUTED_AT_UTC TIMESTAMP(6) NOT NULL,
  STATUS VARCHAR2(20 CHAR) NOT NULL,
  RECORD_COUNT NUMBER(10) NOT NULL,
  DURATION_MS NUMBER(19) NOT NULL,
  ERROR_CATEGORY VARCHAR2(140 CHAR),
  MESSAGE VARCHAR2(1000 CHAR) NOT NULL,
  CONSTRAINT CK_OBS_EXECUTION_STATUS CHECK (STATUS IN ('SUCCESS', 'FAILED'))
);
CREATE INDEX IDX_OBS_COLLECTION_TIME ON OBS_COLLECTION_EXECUTION_LOG (EXECUTED_AT_UTC);

-- Future-phase definitions; schema only, no alerting automation is claimed yet.
CREATE TABLE OBS_SLO_DEFINITION (
  SLO_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  SLO_NAME VARCHAR2(180 CHAR) NOT NULL,
  SERVICE_NAME VARCHAR2(180 CHAR) NOT NULL,
  METRIC_NAME VARCHAR2(200 CHAR) NOT NULL,
  TARGET_PERCENT NUMBER(8,5) NOT NULL,
  WINDOW_DAYS NUMBER(4) NOT NULL,
  IS_ENABLED NUMBER(1) DEFAULT 1 NOT NULL,
  CREATED_AT_UTC TIMESTAMP(6) NOT NULL
);
CREATE TABLE OBS_INCIDENT (
  INCIDENT_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  TITLE VARCHAR2(300 CHAR) NOT NULL,
  SEVERITY VARCHAR2(20 CHAR) NOT NULL,
  STATUS VARCHAR2(30 CHAR) NOT NULL,
  DETECTED_AT_UTC TIMESTAMP(6) NOT NULL,
  RESOLVED_AT_UTC TIMESTAMP(6),
  CORRELATION_ID VARCHAR2(80 CHAR)
);
CREATE TABLE OBS_ALERT_DELIVERY_LOG (
  DELIVERY_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  INCIDENT_ID VARCHAR2(36 CHAR),
  DESTINATION VARCHAR2(80 CHAR) NOT NULL,
  DELIVERY_STATUS VARCHAR2(25 CHAR) NOT NULL,
  ATTEMPTED_AT_UTC TIMESTAMP(6) NOT NULL,
  MESSAGE VARCHAR2(1000 CHAR),
  CONSTRAINT FK_OBS_ALERT_INCIDENT FOREIGN KEY (INCIDENT_ID) REFERENCES OBS_INCIDENT(INCIDENT_ID)
);
CREATE TABLE OBS_AUDIT_LOG (
  AUDIT_ID VARCHAR2(36 CHAR) PRIMARY KEY,
  ACTOR_ID VARCHAR2(160 CHAR),
  ACTION_NAME VARCHAR2(120 CHAR) NOT NULL,
  TARGET_TYPE VARCHAR2(100 CHAR) NOT NULL,
  TARGET_ID VARCHAR2(160 CHAR),
  EVENT_TIME_UTC TIMESTAMP(6) NOT NULL,
  SUMMARY VARCHAR2(1000 CHAR) NOT NULL
);
